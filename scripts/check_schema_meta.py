#!/usr/bin/env python3
"""Drift enforcement for the `meta.business_rules` blocks in config/schemas/*.yml.

Each of the five config/schemas/*.yml reference schemas carries a `meta:` block.
Every `business_rules[]` entry there
carries an `id`, a `source:` pointer of the form
``config/context/<file>.yaml#<id>`` (or, for a feed cutover, a file + a
``(YYYY-MM-DD <label>)`` parenthetical), an `applies_to_columns:` list and a
prose `summary:`. Those blocks are a hand-maintained SECOND COPY of rules whose
SOURCE OF RECORD is config/context/*.yaml (itself rendered from
data/bq-knowledge.md by scripts/export_context.py). This checker makes any drift
between the copy and the source of record fail loudly.

It NEVER writes to config/schemas/*.yml or config/context/*.yaml. It only reads
them and maintains one generated golden lock (config/schemas/schema-meta.lock.json)
that freezes a fingerprint of both sides.
and emits no wall-clock output, so `--check` is stable across runs and in CI.

What it asserts
---------------
HARD checks (fail loudly with an actionable message; run in every mode):

  1. id resolution — every schema business_rules[].id resolves to a real rule in
     the context file its `source:` points at:
       * entity-rules.yaml / integration-payload-traps.yaml  -> resolve by rule id
         (the `#anchor`, or the entry id if the pointer has no anchor); the
         resolved entry's id must equal the schema rule id.
       * feed-cutovers.yaml -> that file carries no id (it is keyed by date), so
         resolve by the YYYY-MM-DD date parsed from the `source:` parenthetical.
       * no recognisable pointer -> search entity-rules + integration-payload-traps
         by the schema rule id.
     A schema rule id that no longer resolves is a real finding (a renamed or
     removed context rule) and fails the check.

  2. column consistency — for entity-rule / integration-payload-trap rules, the
     schema rule's `applies_to_columns` must share at least one column with the
     context entry's `applies_to_columns` (non-empty intersection). This tolerates
     the legitimate table-specific cases (a schema block naming a SUBSET of the
     context columns, or an equivalent table-local column such as
     acme_customer.email_hash that the context entry does not list) while still
     catching a rule whose columns have drifted wholesale away from the source.
     Feed-cutover context entries carry no columns, so this check is skipped for
     them.

SUMMARY comparison rule (documented choice):

  The schema `summary:` is a hand-authored PARAPHRASE of the context `message:` —
  there is no deterministic string relationship between the two, so brittle
  full-string / substring equality is wrong and an LLM "faithfulness" judgement is
  non-deterministic. Instead this checker freezes a STORED HASH of BOTH sides in a
  generated lock file: the normalised (whitespace-collapsed) sha256 of the schema
  summary AND of the resolved context message (or the cutover date|label|effect).
  `--check` recomputes the lock and fails if it differs from the committed one.
  Consequently ANY edit to a schema summary, OR any change to the source-of-record
  message/columns/entity it paraphrases, trips the gate and forces a human to
  re-review the paraphrase and regenerate the lock (`python3
  scripts/check_schema_meta.py`). That is exactly the "second place that
  inevitably drifts" guard the roadmap asks for, in both directions.

Usage
-----
    python3 scripts/check_schema_meta.py           # regenerate the lock, print a summary
    python3 scripts/check_schema_meta.py --check    # exit 1 on any unresolved id,
                                                     # column divergence, or lock drift
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
SCHEMA_DIR = REPO_ROOT / "config" / "schemas"
CONTEXT_DIR = REPO_ROOT / "config" / "context"
LOCK_PATH = SCHEMA_DIR / "schema-meta.lock.json"

ENTITY_RULES = "entity-rules.yaml"
INTEGRATION_TRAPS = "integration-payload-traps.yaml"
FEED_CUTOVERS = "feed-cutovers.yaml"
CONTEXT_FILES = {ENTITY_RULES, INTEGRATION_TRAPS, FEED_CUTOVERS}

SOURCE_FILE_RE = re.compile(r"config/context/(?P<file>[A-Za-z0-9._-]+\.ya?ml)")
SOURCE_ANCHOR_RE = re.compile(r"#(?P<anchor>[A-Za-z0-9_.-]+)")
DATE_RE = re.compile(r"\d{4}-\d{2}-\d{2}")

LOCK_NOTE = (
    "GENERATED by scripts/check_schema_meta.py. Golden fingerprint of the "
    "meta.business_rules blocks in config/schemas/*.yml and the config/context/*.yaml "
    "rules they paraphrase. Do not hand-edit -- regenerate with "
    "`python3 scripts/check_schema_meta.py` and re-review. `--check` fails if this "
    "would change (a schema summary/column edit, or a source-of-record drift)."
)


# --- normalisation / hashing ------------------------------------------------
def _norm(text: str | None) -> str:
    """Collapse all runs of whitespace to single spaces and strip; makes the
    hash insensitive to YAML folded-scalar line wrapping and indentation."""
    return " ".join((text or "").split()).strip()


def _sha(text: str) -> str:
    return hashlib.sha256(_norm(text).encode("utf-8")).hexdigest()


# --- context layer ----------------------------------------------------------
def _load_list(path: Path) -> list[dict]:
    if not path.is_file():
        return []
    return yaml.safe_load(path.read_text(encoding="utf-8")) or []


def load_context() -> dict:
    """Return indexes for the three context files: id-keyed for the two rule
    files, date-keyed for the cutover calendar."""
    entity = {e["id"]: e for e in _load_list(CONTEXT_DIR / ENTITY_RULES) if e.get("id")}
    integration = {e["id"]: e for e in _load_list(CONTEXT_DIR / INTEGRATION_TRAPS) if e.get("id")}
    cutovers = {}
    for c in _load_list(CONTEXT_DIR / FEED_CUTOVERS):
        date = str(c.get("date"))
        if date:
            cutovers[date] = c
    return {"entity": entity, "integration": integration, "cutovers": cutovers}


# --- schema layer -----------------------------------------------------------
def load_schema_rules() -> list[dict]:
    """Every meta.business_rules[] entry across config/schemas/*.yml, tagged with
    its source schema file, in a deterministic order."""
    rules = []
    for path in sorted(SCHEMA_DIR.glob("*.yml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        for model in doc.get("models") or []:
            meta = model.get("meta") or {}
            for br in meta.get("business_rules") or []:
                rules.append(
                    {
                        "schema": path.name,
                        "model": model.get("name"),
                        "id": br.get("id"),
                        "source": br.get("source") or "",
                        "applies_to_columns": list(br.get("applies_to_columns") or []),
                        "summary": br.get("summary") or "",
                    }
                )
    return rules


def parse_source(source: str) -> tuple[str | None, str | None, str | None]:
    """(context_file, anchor_id, date) parsed from a business_rules[].source
    pointer. Any component may be None."""
    fm = SOURCE_FILE_RE.search(source)
    ctx_file = fm.group("file") if fm else None
    am = SOURCE_ANCHOR_RE.search(source)
    anchor = am.group("anchor") if am else None
    dm = DATE_RE.search(source)
    date = dm.group(0) if dm else None
    return ctx_file, anchor, date


# --- resolution + checks ----------------------------------------------------
def resolve_and_check(rules: list[dict], ctx: dict) -> tuple[list[dict], list[str]]:
    """Resolve every schema rule against the context layer and run the HARD
    checks. Returns (lock_records, errors). errors is empty iff every rule
    resolves and its columns are consistent."""
    records: list[dict] = []
    errors: list[str] = []

    for r in rules:
        where = f"{r['schema']} :: business_rules[id={r['id']!r}]"
        if not r["id"]:
            errors.append(f"{r['schema']}: a business_rules entry is missing an `id`.")
            continue

        ctx_file, anchor, date = parse_source(r["source"])
        cols = sorted(r["applies_to_columns"])
        record = {
            "schema": r["schema"],
            "id": r["id"],
            "applies_to_columns": cols,
            "summary_sha256": _sha(r["summary"]),
        }

        if ctx_file == FEED_CUTOVERS:
            if not date:
                errors.append(
                    f"{where}: source points at {FEED_CUTOVERS} but carries no "
                    f"YYYY-MM-DD date to resolve it by (source: {r['source']!r})."
                )
                continue
            entry = ctx["cutovers"].get(date)
            if entry is None:
                errors.append(
                    f"{where}: no feed cutover dated {date} in "
                    f"config/context/{FEED_CUTOVERS} — the rule no longer resolves."
                )
                continue
            record.update(
                source_kind="feed_cutover",
                source_file=FEED_CUTOVERS,
                context_key=date,
                context_entity=None,
                context_columns=[],
                context_sha256=_sha(
                    f"{entry.get('date')}|{entry.get('label')}|{entry.get('effect')}"
                ),
            )
            records.append(record)
            continue

        # entity-rule / integration-payload-trap (or fall back to searching both).
        index = None
        kind = None
        if ctx_file == ENTITY_RULES:
            index, kind = ctx["entity"], "entity_rule"
        elif ctx_file == INTEGRATION_TRAPS:
            index, kind = ctx["integration"], "integration_payload_trap"
        else:
            # No recognisable pointer: search both id-keyed files.
            if r["id"] in ctx["entity"]:
                index, kind, ctx_file = ctx["entity"], "entity_rule", ENTITY_RULES
            elif r["id"] in ctx["integration"]:
                index, kind, ctx_file = ctx["integration"], "integration_payload_trap", INTEGRATION_TRAPS
            else:
                errors.append(
                    f"{where}: source {r['source']!r} names no known context file and "
                    f"the id resolves in neither {ENTITY_RULES} nor {INTEGRATION_TRAPS}."
                )
                continue

        lookup = anchor or r["id"]
        if anchor and anchor != r["id"]:
            errors.append(
                f"{where}: source anchor #{anchor} does not match the rule id "
                f"{r['id']!r} — point the source at #{r['id']}."
            )
            continue
        entry = index.get(lookup)
        if entry is None:
            errors.append(
                f"{where}: id does not resolve to any rule in "
                f"config/context/{ctx_file} — renamed or removed at the source?"
            )
            continue

        ctx_cols = list(entry.get("applies_to_columns") or [])
        if not (set(r["applies_to_columns"]) & set(ctx_cols)):
            errors.append(
                f"{where}: applies_to_columns {r['applies_to_columns']} shares no "
                f"column with the context entry {ctx_cols} in "
                f"config/context/{ctx_file} — columns diverged from the source."
            )
            continue

        record.update(
            source_kind=kind,
            source_file=ctx_file,
            context_key=entry.get("id"),
            context_entity=entry.get("entity"),
            context_columns=sorted(ctx_cols),
            context_sha256=_sha(entry.get("message") or ""),
        )
        records.append(record)

    records.sort(key=lambda rec: (rec["schema"], rec["id"]))
    return records, errors


def build_lock(records: list[dict]) -> str:
    payload = {"note": LOCK_NOTE, "rules": records}
    return json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


# --- CLI --------------------------------------------------------------------
def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 on any unresolved id, column divergence, or lock drift (no write)",
    )
    ap.add_argument(
        "--json",
        action="store_true",
        help="emit structured findings JSON to stdout (for promotion detector)",
    )
    args = ap.parse_args(argv)

    if not SCHEMA_DIR.is_dir():
        print(f"ERROR: {SCHEMA_DIR} not found", file=sys.stderr)
        return 1
    if not CONTEXT_DIR.is_dir():
        print(f"ERROR: {CONTEXT_DIR} not found", file=sys.stderr)
        return 1

    ctx = load_context()
    rules = load_schema_rules()
    records, errors = resolve_and_check(rules, ctx)

    if errors:
        if args.json:
            findings = []
            import re as _re

            rule_re = _re.compile(r"business_rules\[id=['\"]?([^'\"\\]]+)")
            for err in errors:
                m = rule_re.search(err)
                rule_id = m.group(1) if m else None
                if not rule_id:
                    m2 = _re.search(r"id does not resolve.*rule in", err)
                    rule_id = "unresolved-rule" if m2 else "schema-meta-error"
                findings.append(
                    {
                        "rule_id": rule_id,
                        "message": err,
                        "resolved": False,
                    }
                )
            print(json.dumps({"ok": False, "findings": findings, "errors": errors}, indent=2))
            return 1
        print("SCHEMA META DRIFT — config/schemas/*.yml meta.business_rules diverged "
              "from config/context/*.yaml:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        return 1

    new_lock = build_lock(records)

    if args.check:
        old_lock = LOCK_PATH.read_text(encoding="utf-8") if LOCK_PATH.is_file() else None
        if old_lock != new_lock:
            if args.json:
                print(
                    json.dumps(
                        {
                            "ok": False,
                            "findings": [
                                {
                                    "rule_id": "schema-meta-lock-drift",
                                    "message": "schema-meta.lock.json would change",
                                    "resolved": False,
                                }
                            ],
                            "lock_drift": True,
                        },
                        indent=2,
                    )
                )
                return 1
            print(
                f"OUT OF DATE: {LOCK_PATH.name} would change — a schema summary/column "
                "was edited or a source-of-record rule drifted. Review the schema "
                "meta.business_rules against config/context/*.yaml, then run: "
                "python3 scripts/check_schema_meta.py"
            )
            return 1
        if args.json:
            print(json.dumps({"ok": True, "findings": [], "records": len(records)}, indent=2))
            return 0
        print(f"Up to date. {len(records)} schema business rule(s) resolve and match the lock.")
        return 0

    LOCK_PATH.write_text(new_lock, encoding="utf-8")
    by_kind: dict[str, int] = {}
    for rec in records:
        by_kind[rec["source_kind"]] = by_kind.get(rec["source_kind"], 0) + 1
    kinds = ", ".join(f"{k}: {v}" for k, v in sorted(by_kind.items()))
    print(
        f"Wrote {LOCK_PATH.relative_to(REPO_ROOT)} — {len(records)} schema business "
        f"rule(s) across {len({r['schema'] for r in records})} schema file(s) all "
        f"resolve against config/context/*.yaml ({kinds})."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
