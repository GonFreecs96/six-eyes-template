#!/usr/bin/env python3
"""Export the machine-consultable subset of data/bq-knowledge.md into
config/context/*.yaml.

bq-knowledge.md stays the single human-authored source -- no parallel registry.
The YAML is rendered FROM it (the same pattern a governed metrics repo uses for
its structured files) rather than hand-maintained alongside it; see
docs/ARCHITECTURE.md "Context layer".

Two input shapes in bq-knowledge.md:

1. The "## Feed cutovers & temporal discontinuities" markdown table -- already
   structured (Date | Change | Effect), parsed directly, no tagging needed.
2. Inline `<!-- ctx: id=<slug> entity=<entity> category=<entity_rule|
   instrumentation_gap|integration_payload_trap> cols=<comma,list> -->` tags
   (instrumentation_gap entries are written to entity-rules.yaml) appended to selected
   high-value bullets/table-cells elsewhere in the file -- the "machine-
   consultable subset" the roadmap calls for. Not every bq-knowledge.md entry
   is tagged; only the ones that are genuinely rule-like (would belong in a
   guardrails-style layer), not narrative one-off investigation results.

This script only *reads* bq-knowledge.md and *writes* config/context/*.yaml.
It never writes back to bq-knowledge.md. Re-run any time bq-knowledge.md
changes; output is fully regenerated (not hand-edited) each run.

Usage:
    python3 scripts/export_context.py           # write the 3 files, print a summary
    python3 scripts/export_context.py --check   # exit 1 if output would change (CI-style)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
BQ_KNOWLEDGE = REPO_ROOT / "data" / "bq-knowledge.md"
CONTEXT_DIR = REPO_ROOT / "config" / "context"

CTX_TAG_RE = re.compile(
    r"<!--\s*ctx:\s*id=(?P<id>\S+)\s+entity=(?P<entity>\S+)\s+"
    r"category=(?P<category>\S+)\s+cols=(?P<cols>\S+)\s*-->"
)
SOURCE_RE = re.compile(r"\*\*Source:\*\*\s*(?P<source>.+?)\.?\s*$")
LEADING_BULLET_RE = re.compile(r"^\s*-\s+")
LEADING_TABLE_CELL_RE = re.compile(r"^\|[^|]*\|\s*")

FEED_CUTOVER_ROW_RE = re.compile(
    r"^\|\s*(?P<date>[^|]+?)\s*\|\s*(?P<change>.+?)\s*\|\s*(?P<effect>.+?)\s*\|\s*$"
)
# Accepted Date-cell shapes: `2026-08-31`, `~2026-08-31`, `2026-03`,
# `2026-03 (approx)`, and ranges like `2026-02 → 2026-03`.
DATE_POINT_RE = re.compile(r"(\d{4})-(\d{2})(?:-(\d{2}))?")
APPROX_MARK_RE = re.compile(r"^~|\(approx\.?\)|\bapprox\b|→|–|\s-\s", re.I)

HEADER_COMMENT = (
    "# AUTO-GENERATED by scripts/export_context.py from data/bq-knowledge.md.\n"
    "# Do not hand-edit -- edit the tagged entry in bq-knowledge.md and re-run\n"
    "# the export script instead. bq-knowledge.md remains the single source;\n"
    "# this file is a rendered, machine-consultable view of a subset of it.\n"
)


def extract_message_and_source(line: str, tag_start: int) -> tuple[str, str | None]:
    """Given the raw line and the character offset where the ctx tag begins,
    return (message, source) with list/table-cell markup stripped and any
    **Source:** citation pulled into its own field. The tag is usually at the
    end of the claim, but a few entries have trailing context after it (and
    thus after the Source citation too) -- search the whole line for Source
    so those aren't lost, while the message itself is still only the text
    up to the tag (the claim, not the trailing context)."""
    text = line[:tag_start].rstrip()
    text = LEADING_TABLE_CELL_RE.sub("", text)
    text = LEADING_BULLET_RE.sub("", text)

    source = None
    m = SOURCE_RE.search(text)
    if m:
        source = m.group("source").strip()
        text = text[: m.start()].rstrip()
    else:
        # Source citation may sit after the tag (trailing-context entries).
        rest_of_line = line[tag_start:]
        m2 = re.search(r"\*\*Source:\*\*\s*(?P<source>.+?)\.?\s*$", rest_of_line)
        if m2:
            source = m2.group("source").strip()

    # Drop markdown bold markers for a cleaner machine-consultable string;
    # keep backticks (column/value names read better with them intact).
    text = text.replace("**", "").strip()
    return text, source


def _looks_like_placeholder(*values: str) -> bool:
    """The tag convention is documented inline in bq-knowledge.md's own header
    using literal placeholder syntax (e.g. `id=<slug> ... category=<entity_rule|
    integration_payload_trap>`), which the tag regex would otherwise happily parse
    as a real tag. Real ids/entities/categories never contain `<`, `>`, or `|`
    -- skip anything that does."""
    return any(c in v for v in values for c in "<>|")


def _parent_bullet_message(lines: list[str], idx: int) -> str:
    """For a tag on a nested `- **Source:** ...` sub-bullet, the claim is the
    nearest preceding bullet at a shallower indent (the entry's headline)."""
    indent = len(lines[idx]) - len(lines[idx].lstrip())
    for prev in reversed(lines[:idx]):
        if not prev.strip():
            break
        prev_indent = len(prev) - len(prev.lstrip())
        if prev_indent < indent and LEADING_BULLET_RE.match(prev):
            text = LEADING_BULLET_RE.sub("", prev)
            return text.replace("**", "").strip()
    return ""


def parse_ctx_tags(content: str) -> list[dict]:
    entries = []
    lines = content.splitlines()
    for idx, line in enumerate(lines):
        m = CTX_TAG_RE.search(line)
        if not m:
            continue
        if _looks_like_placeholder(m.group("id"), m.group("entity"), m.group("category")):
            continue
        message, source = extract_message_and_source(line, m.start())
        if not message:
            message = _parent_bullet_message(lines, idx)
        entries.append(
            {
                "id": m.group("id"),
                "entity": m.group("entity"),
                "category": m.group("category"),
                "applies_to_columns": m.group("cols").split(","),
                "message": message,
                "source": source,
            }
        )
    return entries


def parse_date_cell(cell: str) -> tuple[str, bool] | None:
    """Return (iso_date, approximate) for a feed-cutover Date cell, or None.

    Downstream consumers (check_schema_meta, governed promotion) need an ISO date,
    so an imprecise cell resolves to its EARLIEST possible day: a month-only
    date becomes the 1st, a range its start. Erring early means a query window
    that might straddle the change still gets warned.
    """
    first = DATE_POINT_RE.search(cell)
    if not first:
        return None
    year, month, day = first.groups()
    iso = f"{year}-{month}-{day or '01'}"
    exact = day is not None and cell.strip() == first.group(0)
    return iso, not exact or bool(APPROX_MARK_RE.search(cell))


def parse_feed_cutovers(content: str) -> list[dict]:
    section = content.split("## Feed cutovers & temporal discontinuities", 1)
    if len(section) < 2:
        return []
    body = section[1].split("\n---", 1)[0]
    rows = []
    for line in body.splitlines():
        m = FEED_CUTOVER_ROW_RE.match(line.strip())
        if not m:
            continue
        date_cell, change, effect = m.group("date"), m.group("change"), m.group("effect")
        parsed = parse_date_cell(date_cell)
        if parsed is None:
            continue
        date, approximate = parsed
        source = None
        sm = SOURCE_RE.search(effect)
        if sm:
            source = sm.group("source").strip()
            effect = effect[: sm.start()].rstrip()
        row = {
            "date": date,
            "label": change.replace("**", "").strip(),
            "effect": effect.replace("**", "").strip(),
            "source": source,
        }
        if approximate:
            row["date_display"] = date_cell.strip()
            row["approximate"] = True
        rows.append(row)
    return rows


def build_yaml(entries: list[dict], extra_header: str) -> str:
    body = yaml.safe_dump(entries, sort_keys=False, allow_unicode=True, width=100)
    return HEADER_COMMENT + extra_header + "\n" + body


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if regenerated output differs from what's on disk (no write)",
    )
    ap.add_argument(
        "--json",
        action="store_true",
        help="emit structured drift JSON to stdout (for promotion detector)",
    )
    args = ap.parse_args(argv)

    if not BQ_KNOWLEDGE.is_file():
        print(f"ERROR: {BQ_KNOWLEDGE} not found", file=sys.stderr)
        return 1

    content = BQ_KNOWLEDGE.read_text(encoding="utf-8")
    ctx_entries = parse_ctx_tags(content)
    cutovers = parse_feed_cutovers(content)

    # instrumentation_gap entries ("this isn't capturable in the warehouse") are
    # entity-anchored warnings too, so they ride in entity-rules.yaml with their
    # own category label preserved.
    entity_rules = [e for e in ctx_entries if e["category"] in ("entity_rule", "instrumentation_gap")]
    integration_traps = [e for e in ctx_entries if e["category"] == "integration_payload_trap"]
    unknown = [
        e for e in ctx_entries
        if e["category"] not in ("entity_rule", "instrumentation_gap", "integration_payload_trap")
    ]
    if unknown:
        print(f"WARNING: {len(unknown)} ctx tag(s) with unrecognized category: "
              f"{[e['id'] for e in unknown]}", file=sys.stderr)
    empty = [e["id"] for e in ctx_entries if not e["message"]]
    if empty:
        print(f"ERROR: ctx tag(s) with empty message (tag a line that carries the claim): "
              f"{empty}", file=sys.stderr)
        return 1

    outputs = {
        CONTEXT_DIR / "feed-cutovers.yaml": build_yaml(
            cutovers,
            "# Feed / pipeline discontinuity calendar. A query whose time window\n"
            "# straddles one of these dates sees a step-change that is an artifact,\n"
            "# not behavior. Parsed from bq-knowledge.md's own markdown table.\n",
        ),
        CONTEXT_DIR / "entity-rules.yaml": build_yaml(
            entity_rules,
            "# Entity-anchored business rules — load-bearing facts keyed to an entity\n"
            "# and the column(s) they govern. Rendered from tagged entries in bq-knowledge.md.\n",
        ),
        CONTEXT_DIR / "integration-payload-traps.yaml": build_yaml(
            integration_traps,
            "# Integration-specific payload/shape gotchas — same event name or table,\n"
            "# different JSON shape or enum values per partner or client surface.\n"
            "# Audit cross-partner rollups and hardcoded JSON paths against this list.\n",
        ),
    }

    if args.check:
        deltas: list[dict] = []
        for path, new_content in outputs.items():
            old_content = path.read_text(encoding="utf-8") if path.is_file() else None
            if old_content != new_content:
                rel = str(path.relative_to(REPO_ROOT))
                deltas.append({"file": path.name, "path": rel})
        if args.json:
            print(json.dumps({"ok": not deltas, "deltas": deltas}, indent=2))
            return 0 if not deltas else 1
        if deltas:
            names = [d["file"] for d in deltas]
            print(f"OUT OF DATE: {names} would change. Run without --check to regenerate.")
            return 1
        print("Up to date.")
        return 0

    CONTEXT_DIR.mkdir(parents=True, exist_ok=True)
    for path, new_content in outputs.items():
        path.write_text(new_content, encoding="utf-8")

    print(f"Exported {len(cutovers)} feed cutover(s), {len(entity_rules)} entity rule(s), "
          f"{len(integration_traps)} integration payload trap(s) to {CONTEXT_DIR}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
